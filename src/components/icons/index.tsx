/**
 * Figma 아이콘(SVG) 경로를 그대로 옮긴 아이콘 세트.
 * 색은 currentColor라서 text-* 토큰으로 지정합니다.
 * size를 바꿔도 Figma와 같은 획 두께(px)를 유지하도록 strokeWidth를 보정합니다.
 */
export type IconProps = Omit<SVGProps<SVGSVGElement>, 'children'> & { size?: number };

function createStrokeIcon(
  displayName: string,
  baseSize: number,
  paths: string[],
  { strokeWidth = 1.8, viewBox }: { strokeWidth?: number; viewBox?: string } = {},
) {
  function Icon({ size = baseSize, ...rest }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox={viewBox ?? `0 0 ${baseSize} ${baseSize}`}
        fill="none"
        stroke="currentColor"
        strokeWidth={(strokeWidth * baseSize) / size}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        focusable={false}
        {...rest}
      >
        {paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  }
  Icon.displayName = displayName;
  return Icon;
}

